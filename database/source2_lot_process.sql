SELECT a.*,
  a.LOT || ':' || TO_CHAR(a.OPERATION_SEQ, 'TM9') AS SOURCE_KEY,
  a.LOT AS LOT_NO,
  a.LOT AS SOURCE_LOT_NO,
  COALESCE(TRIM(a.OPERATION_DESC), a.OPERATION_CODE, a.WIP_OPTN_CODE) AS PROCESS_NAME,
  a.OPERATION_CODE AS PROCESS_CODE,
  a.OPERATION_SEQ AS OPERATION_SEQUENCE,
  a.MACHINE AS MACHINE_ID,
  a.QTY_IN AS INPUT_QTY,
  a.QTY_OUT AS OUTPUT_QTY,
  a.QTY_REJECT AS REJECT_QTY,
  a.DATETIME_IN AS STARTED_AT,
  a.DATETIME_OUT AS COMPLETED_AT,
  a.LP_STATUS AS STATUS,
  a.EN AS OPERATOR
FROM PROMIS2.BWIP_LOT_PROCESS a
WHERE a.LOT IN (:LOT_LIST)
  AND a.AREA_CODE <> 'TEST'
ORDER BY a.LOT, a.OPERATION_SEQ ASC
