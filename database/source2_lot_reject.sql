SELECT b.LOT, b.OPERATION_CODE, b.WIP_OPTN_CODE, b.OPERATION_SEQ,
       b.REJECT_CODE, b.REJECT_DESCRIPTION, b.REJECT_QTY, b.REWORK_QTY,
       b.EXT_REJ_CODE, b.EXT_REJ_DESC,
       b.LOT AS LOT_NO, b.LOT AS SOURCE_LOT_NO,
       LENGTH(b.LOT) || ':' || b.LOT || ':' || LENGTH(b.OPERATION_CODE) || ':' || b.OPERATION_CODE || ':' || LENGTH(b.REJECT_CODE) || ':' || b.REJECT_CODE AS SOURCE_KEY,
       COALESCE(TRIM(p.OPERATION_DESC), b.OPERATION_CODE) AS PROCESS_NAME,
       b.OPERATION_CODE AS PROCESS_CODE,
       b.OPERATION_SEQ AS OPERATION_SEQUENCE,
       CASE WHEN p.LOT IS NOT NULL THEN p.LOT || ':' || TO_CHAR(p.OPERATION_SEQ, 'TM9') END AS PROCESS_SOURCE_KEY,
       p.AREA_CODE AS PROCESS_AREA_CODE,
       p.MACHINE AS MACHINE_ID,
       p.DATETIME_OUT AS TRANSACTION_DATE,
       b.REJECT_CODE AS DEFECT_CODE,
       COALESCE(TRIM(b.REJECT_DESCRIPTION), b.REJECT_CODE) AS DEFECT_DESCRIPTION,
       b.REJECT_QTY AS QTY
FROM PROMIS.BWIP_LOT_REJECT b
LEFT JOIN PROMIS2.BWIP_LOT_PROCESS p
       ON p.LOT = b.LOT AND p.OPERATION_SEQ = b.OPERATION_SEQ
       AND p.OPERATION_CODE = b.OPERATION_CODE
WHERE b.LOT IN (:LOT_LIST)
ORDER BY b.LOT, b.OPERATION_SEQ ASC, b.OPERATION_CODE, b.REJECT_CODE
