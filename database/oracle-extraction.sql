-- Replace source object and column names after validating ACTL/BSM data dictionaries.
-- SOURCE_KEY must identify the operation record, not merely the lot.
-- LAST_UPDATE_DATE must track all corrections; TRANSACTION_DATE must be immutable.
SELECT TRANSACTION_ID AS SOURCE_KEY, LOT_NO, CUSTOMER, PRODUCT, PACKAGE,
 DEVICE, TECHNOLOGY, BOM, BOM_REVISION, FACTORY, LINE, SHIFT, OPERATOR,
 PROCESS_NAME, MACHINE_ID, INPUT_QTY, OUTPUT_QTY, REJECT_QTY, REWORK_QTY,
 UNIT_COST, TRANSACTION_DATE
FROM LOT_HISTORY
WHERE LAST_UPDATE_DATE >= :LAST_SYNC_TIME
  AND LAST_UPDATE_DATE < :SYNC_END_TIME
ORDER BY LAST_UPDATE_DATE, TRANSACTION_ID;

SELECT DEFECT_TRANSACTION_ID AS SOURCE_KEY, LOT_NO, PROCESS_NAME, MACHINE_ID,
 DEFECT_CODE, DEFECT_DESCRIPTION, QTY, TRANSACTION_DATE
FROM DEFECT_HISTORY
WHERE LAST_UPDATE_DATE >= :LAST_SYNC_TIME AND LAST_UPDATE_DATE < :SYNC_END_TIME;

SELECT SCRAP_TRANSACTION_ID AS SOURCE_KEY, LOT_NO, PROCESS_NAME,
 SCRAP_QTY, SCRAP_REASON, TRANSACTION_DATE
FROM SCRAP_HISTORY
WHERE LAST_UPDATE_DATE >= :LAST_SYNC_TIME AND LAST_UPDATE_DATE < :SYNC_END_TIME;

SELECT MEASUREMENT_ID AS SOURCE_KEY, PROCESS_NAME, MACHINE_ID,
 MEASUREMENT_NAME, MEASUREMENT_VALUE, UCL, LCL, TARGET, SAMPLE_SIZE,
 SUBGROUP, TRANSACTION_DATE
FROM SPC_HISTORY
WHERE LAST_UPDATE_DATE >= :LAST_SYNC_TIME AND LAST_UPDATE_DATE < :SYNC_END_TIME;
